#!/usr/bin/env node
/**
 * Renders ../CHANGELOG.md into docs/changelog.html.
 *
 * Generated rather than hand-written so the published page cannot drift from
 * the source of truth. Re-run with `npm run docs:changelog` after editing the
 * changelog.
 */
const fs = require('fs');
const path = require('path');

const md = fs.readFileSync(path.join(__dirname, '..', 'CHANGELOG.md'), 'utf8');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Inline: `code`, **bold**, [text](url). Escaping happens first, so the markup
// below is the only HTML that survives.
function inline(s) {
  return esc(s)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');
}

const out = [];
let inList = false;
const closeList = () => { if (inList) { out.push('</ul>'); inList = false; } };

for (const raw of md.split('\n')) {
  const line = raw.trimEnd();
  if (/^---\s*$/.test(line)) { closeList(); continue; }

  let m;
  if ((m = line.match(/^#\s+(.*)/))) { closeList(); continue; }        // page title comes from the template
  if ((m = line.match(/^##\s+(.*)/))) {
    closeList();
    out.push(`<h2 id="${m[1].toLowerCase().replace(/[^\w]+/g, '-').replace(/^-|-$/g, '')}">${inline(m[1])}</h2>`);
    continue;
  }
  if ((m = line.match(/^###\s+(.*)/))) { closeList(); out.push(`<h3>${inline(m[1])}</h3>`); continue; }
  if ((m = line.match(/^[-*]\s+(.*)/))) {
    if (!inList) { out.push('<ul>'); inList = true; }
    out.push(`<li>${inline(m[1])}</li>`);
    continue;
  }
  if (line === '') { closeList(); continue; }
  closeList();
  out.push(`<p>${inline(line)}</p>`);
}
closeList();

const nav = (cur) => ['index.html:Home', 'guide.html:Quick start', 'support.html:Setup &amp; FAQ', 'privacy.html:Privacy', 'changelog.html:Changelog']
  .map((e) => { const [h, t] = e.split(':'); return `      <a href="${h}"${h === cur ? ' aria-current="page"' : ''}>${t}</a>`; })
  .join('\n');

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Changelog — Review Atlas</title>
<meta name="description" content="Every change to Review Atlas, by version." />
<link rel="icon" href="assets/icon.png" />
<link rel="stylesheet" href="site.css" />
</head>
<body>

<header class="site-header">
  <div class="wrap nav">
    <a class="brand" href="index.html"><img src="assets/icon.png" alt="" /><span>Review Atlas</span></a>
    <nav class="nav-links">
${nav('changelog.html')}
      <a href="https://github.com/lauming1111/ReviewAtlas">Source</a>
    </nav>
  </div>
</header>

<main class="wrap">
<article class="prose" style="padding:44px 0">
  <h1>Changelog</h1>
  <p class="updated">Generated from CHANGELOG.md — do not edit this file by hand.</p>
${out.map((l) => '  ' + l).join('\n')}
</article>
</main>

<footer class="site-footer">
  <div class="wrap footer-inner">
    <p>© 2026 minglau0315 · Source available, not open source — see the <a href="https://github.com/lauming1111/ReviewAtlas/blob/main/LICENSE">licence</a>.</p>
    <nav class="footer-links">
      <a href="index.html">Home</a>
      <a href="privacy.html">Privacy</a>
      <a href="support.html">Support</a>
      <a href="https://github.com/lauming1111/ReviewAtlas">GitHub</a>
    </nav>
  </div>
</footer>

</body>
</html>
`;

fs.writeFileSync(path.join(__dirname, 'changelog.html'), html);
console.log(`Rendered changelog.html (${out.length} blocks)`);
